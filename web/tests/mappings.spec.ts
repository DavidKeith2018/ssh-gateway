test('打开映射在新标签页访问真实网页，原工作区保持可用', async ({ page }) => {
  const fixture = JSON.parse(readFileSync('.test-fixture/connection.json', 'utf8'))
  const server = http.createServer((_req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end('<h1>端口映射网页验收</h1>') })
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve))
  const servicePort = (server.address() as net.AddressInfo).port
  const ids: string[] = []
  try {
    await page.goto('/'); await page.getByLabel('管理员密码').fill(fixture.admin_password); await page.getByRole('button', { name: '进入中转台' }).click()
    await expect(page.getByRole('heading', { name: 'SSH 连接', exact: true })).toBeVisible()
    const target = await page.request.post('/api/targets', { data: fixture.mapping_target }); expect(target.ok(), await target.text()).toBeTruthy()
    await page.reload(); await page.locator('.nav-item').filter({ hasText: '端口映射' }).click()
    const overview = page.getByRole('region', { name: '端口映射总览' })
    for (const direction of ['local', 'reverse']) {
      const port = await unusedPort(), name = `${direction} 网页验收`
      const created = await page.request.post('/api/mappings', { data: { target_id: fixture.mapping_target.id, name, direction, service_host: '127.0.0.1', service_port: servicePort, listen_port: port, scope: direction === 'local' ? 'loopback' : 'shared', auto_start: false } })
      expect(created.ok(), await created.text()).toBeTruthy()
      const { id } = await created.json(); ids.push(id)
      const started = await page.request.post(`/api/mappings/${id}/start`, { data: {} }); expect(started.ok()).toBeTruthy()
      const row = overview.locator('tbody tr').filter({ hasText: name }); await expect(row).toContainText('运行中')
      const link = row.getByRole('link', { name: '打开' }); await expect(link).toHaveAttribute('rel', 'noopener noreferrer')
      const popupPromise = page.waitForEvent('popup'); await link.click(); const popup = await popupPromise
      await expect(popup.getByRole('heading', { name: '端口映射网页验收' })).toBeVisible()
      await expect(overview).toBeVisible(); await popup.close()
    }
  } finally {
    for (const id of ids) expect((await page.request.delete(`/api/mappings/${id}`, { data: {} })).ok()).toBeTruthy()
    expect((await page.request.delete(`/api/targets/${fixture.mapping_target.id}`, { data: {} })).ok()).toBeTruthy()
    server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve()))
  }
})

