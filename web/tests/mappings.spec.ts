async function unusedPort(): Promise<number> { return new Promise((resolve, reject) => { const server = net.createServer(); server.on('error', reject); server.listen(0, '127.0.0.1', () => { const port = (server.address() as net.AddressInfo).port; server.close(() => resolve(port)) }) }) }
async function echo(port: number): Promise<string> { return new Promise((resolve, reject) => { const socket = net.connect(port, '127.0.0.1', () => socket.write('真实浏览器转发')); socket.setTimeout(3000, () => { socket.destroy(); reject(new Error('转发超时')) }); socket.on('error', reject); socket.on('data', data => { socket.destroy(); resolve(data.toString()) }) }) }
